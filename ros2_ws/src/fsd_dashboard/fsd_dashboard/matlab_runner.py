"""Run LR26_LapSim in the real MATLAB, in the background (dashboard "Vehicle setup").

WSL + Windows MATLAB (the usual setup):
  * MATLAB is found under C:\\Program Files\\MATLAB\\R*\\bin\\matlab.exe (newest release), or set
    FSG_MATLAB to matlab.exe (Windows or /mnt/c path) or to a Linux `matlab`.
  * lapsim/LR26_LapSim is copied to a Windows folder (FSG_MATLAB_WORKDIR, default
    %LOCALAPPDATA%\\fsg-dv-sim\\matlab) before every run, so MATLAB never works on a
    \\\\wsl.localhost path and always sees the current lr26_params.m.
  * A job script applies the parameter changes with lts_set_param (and the event utilisation in
    the competition struct), runs lts_run_all and writes the results table as CSV.

One job runs at a time; a newer request replaces a waiting one (the latest parameters win).
"""

from __future__ import annotations

import csv
import glob
import os
import re
import shutil
import subprocess
import threading
import time

from fsdsim.perf.lapsim import matlab_change

TIMEOUT_S = 900.0


def _run(cmd, **kw) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=20, **kw).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def _release_key(path: str):
    m = re.search(r"R(\d{4})([ab])", path)
    return (int(m.group(1)), m.group(2)) if m else (0, "")


def find_matlab() -> tuple[str | None, str]:
    """(executable, kind) with kind 'windows' (matlab.exe through WSL interop) or 'native'."""
    env = os.environ.get("FSG_MATLAB", "").strip()
    if env:
        if re.match(r"^[A-Za-z]:\\", env):
            env = _run(["wslpath", "-u", env]) or env
        if os.path.exists(env):
            return env, ("windows" if env.lower().endswith(".exe") else "native")
    cands = glob.glob("/mnt/[a-z]/Program Files/MATLAB/R*/bin/matlab.exe")
    if cands:
        return sorted(cands, key=_release_key)[-1], "windows"
    native = shutil.which("matlab")
    if native:
        return native, "native"
    return None, ""


def _win_path(path: str) -> str:
    return _run(["wslpath", "-w", path]) or path


def windows_workdir() -> str | None:
    """WSL path of the Windows folder MATLAB works in."""
    env = os.environ.get("FSG_MATLAB_WORKDIR", "").strip()
    if env:
        return _run(["wslpath", "-u", env]) if re.match(r"^[A-Za-z]:\\", env) else env
    local = _run(["cmd.exe", "/c", "echo %LOCALAPPDATA%"], cwd="/mnt/c") if os.path.isdir("/mnt/c") else ""
    local = local.splitlines()[-1].strip() if local else ""
    if not local or "%" in local:
        return None
    u = _run(["wslpath", "-u", local])
    return os.path.join(u, "fsg-dv-sim", "matlab") if u else None


def _mq(path: str) -> str:
    """Path as a MATLAB single-quoted string literal."""
    return "'" + path.replace("'", "''") + "'"


def job_script(lapsim_dir: str, competition_fn: str, changes, csv_path: str, done_path: str) -> str:
    """MATLAB code of one job (paths as MATLAB sees them)."""
    lines = [
        "% generated by fsd_dashboard (Vehicle setup) - runs LR26_LapSim with the dashboard's parameters",
        "try",
        f"    cd({_mq(lapsim_dir)});",
        "    startup_lapsim;",
        "    veh = lr26_params();",
        f"    comp = {competition_fn}();",
    ]
    lines += ["    " + matlab_change(c) for c in changes]
    lines += [
        "    [~, tbl, total] = lts_run_all(veh, comp);",
        f"    writetable(tbl, {_mq(csv_path)});",
        f"    fid = fopen({_mq(done_path)}, 'w'); fprintf(fid, 'ok\\n%.6f\\n', total); fclose(fid);",
        "catch err",
        f"    fid = fopen({_mq(done_path)}, 'w');",
        "    fprintf(fid, 'error\\n%s\\n', getReport(err, 'extended', 'hyperlinks', 'off')); fclose(fid);",
        "end",
    ]
    return "\n".join(lines) + "\n"


def read_results(csv_path: str) -> dict:
    """lts_run_all table -> {event: {T, points, lap, laps, v_avg, v_max, energy_kwh}}."""
    out = {}
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            def num(k):
                try:
                    return float(row.get(k, ""))
                except ValueError:
                    return None
            out[row.get("Event", "").strip()] = {
                "T": num("Time_s"), "points": num("Points"), "lap": num("Lap_s"), "laps": num("Laps"),
                "v_avg_kmh": num("Vavg_kmh"), "v_max_kmh": num("Vmax_kmh"), "energy_kwh": num("Energy_kWh")}
    return out


class MatlabRunner:
    def __init__(self, lapsim_dir: str, competition_fn: str = "competition_fsa2025", on_change=None,
                 instance: str = "dashboard"):
        """instance: own subfolder of the work folder, so the dashboard and the DV launcher can both run
        MATLAB without overwriting each other's copy of LR26_LapSim or job files."""
        self.lapsim_dir = lapsim_dir
        self.instance = re.sub(r"[^\w-]", "", instance) or "dashboard"
        self.competition_fn = competition_fn
        self.on_change = on_change or (lambda: None)
        self._lock = threading.Lock()
        self._pending: tuple | None = None
        self._busy = False
        self._seq = 0
        self._proc: subprocess.Popen | None = None
        self.exe, self.kind = find_matlab()
        self.workdir: str | None = None
        self.state: dict = {"state": "idle" if self.exe else "unavailable", "matlab": self.exe or "",
                            "message": "" if self.exe else
                            "MATLAB not found: set FSG_MATLAB to matlab.exe (e.g. C:\\Program Files\\MATLAB\\R2025b\\bin\\matlab.exe)"}

    def base_dir(self) -> str | None:
        """Where this runner's jobs and LR26_LapSim copy live (WSL path), once known."""
        if self.workdir is None:
            if self.kind == "windows":
                w = windows_workdir()
                self.workdir = os.path.join(w, self.instance) if w else None
            elif self.kind:
                self.workdir = os.path.join(os.path.expanduser("~"), ".cache", "fsg-dv-sim", "matlab", self.instance)
        return self.workdir

    @property
    def jobs_dir(self) -> str | None:
        b = self.base_dir()
        return os.path.join(b, "jobs") if b else None

    @property
    def available(self) -> bool:
        return self.exe is not None

    def status(self) -> dict:
        with self._lock:
            return dict(self.state)

    def _set(self, **kw) -> None:
        with self._lock:
            self.state.update(kw)
        self.on_change()

    def submit(self, changes, tag: str = "") -> int | None:
        """Queue a run with these changes (strings as in the simulator). Returns the job number."""
        if not self.available:
            return None
        with self._lock:
            self._seq += 1
            job = (self._seq, list(changes), tag)
            self._pending = job
            start = not self._busy
            if start:
                self._busy = True
        if start:
            threading.Thread(target=self._worker, name="matlab-runner", daemon=True).start()
        else:
            self._set(message=f"queued after the running job (#{job[0]})")
        return job[0]

    def cancel(self) -> None:
        with self._lock:
            self._pending = None
            p = self._proc
        if p and p.poll() is None:
            p.kill()

    # ------------------------------------------------------------------ #
    def _worker(self) -> None:
        while True:
            with self._lock:
                job, self._pending = self._pending, None
                if job is None:
                    self._busy = False
                    return
            self._run_job(*job)

    def _run_job(self, seq: int, changes: list, tag: str) -> None:
        t0 = time.time()
        self._set(state="starting", job=seq, tag=tag, changes=changes, started=t0, finished=None, results=None,
                  total=None, message="copying LR26_LapSim for MATLAB")
        try:
            if not self.base_dir():
                raise RuntimeError("cannot find a Windows folder for MATLAB (set FSG_MATLAB_WORKDIR)")
            stage = os.path.join(self.workdir, "LR26_LapSim")
            jobs = os.path.join(self.workdir, "jobs")
            os.makedirs(jobs, exist_ok=True)
            if os.path.isdir(stage):
                shutil.rmtree(stage, ignore_errors=True)
            shutil.copytree(self.lapsim_dir, stage, ignore=shutil.ignore_patterns("*.asv", "slprj", "*.slxc"))
            name = f"fsg_job_{seq}"
            job_m = os.path.join(jobs, name + ".m")
            csv_p, done_p, log_p = (os.path.join(jobs, f"{name}{ext}") for ext in ("_results.csv", "_done.txt", "_log.txt"))
            for f in (csv_p, done_p):
                if os.path.exists(f):
                    os.remove(f)
            self._set(csv=csv_p, log=log_p, script=job_m)
            conv = _win_path if self.kind == "windows" else (lambda p: p)
            with open(job_m, "w", encoding="utf-8") as f:
                f.write(job_script(conv(stage), self.competition_fn, changes, conv(csv_p), conv(done_p)))
            cmd = [self.exe, "-batch", f"run({_mq(conv(job_m))})"]
            self._set(state="running", message=f"MATLAB running ({os.path.basename(os.path.dirname(os.path.dirname(self.exe)))})")
            with open(log_p, "w", encoding="utf-8") as log:
                self._proc = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT,
                                              cwd="/mnt/c" if self.kind == "windows" else self.workdir)
                try:
                    rc = self._proc.wait(timeout=TIMEOUT_S)
                except subprocess.TimeoutExpired:
                    self._proc.kill()
                    raise RuntimeError(f"MATLAB did not finish within {TIMEOUT_S:.0f} s") from None
            if not os.path.exists(done_p):
                tail = open(log_p, encoding="utf-8", errors="replace").read()[-1500:]
                raise RuntimeError(f"MATLAB exited (code {rc}) without results.\n{tail}".strip())
            done = open(done_p, encoding="utf-8", errors="replace").read().splitlines()
            if not done or done[0].strip() != "ok":
                raise RuntimeError("MATLAB error:\n" + "\n".join(done[1:])[:2000])
            res = read_results(csv_p)
            total = float(done[1]) if len(done) > 1 else sum(r["points"] or 0 for r in res.values())
            self._set(state="done", results=res, total=total, finished=time.time(),
                      message=f"MATLAB finished in {time.time() - t0:.0f} s")
        except Exception as e:  # noqa: BLE001
            self._set(state="error", finished=time.time(), message=str(e))
        finally:
            self._proc = None
